def automations():
    return [{"name": a["name"], "description": a["description"], "kind": "github", "intervalSeconds": 60,
             "events": a["events"], "filters": a["filters"], "task": a["task"], "enable": True} for a in AUTOMATIONS]


def load_project(path: Path):
    if not path.exists():
        return Project()
    spec = importlib.util.spec_from_file_location("centurion_project", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    project = getattr(module, "PROJECT", None)
    if not isinstance(project, Project):
        raise SystemExit(f"{path}: define PROJECT = <a centurion.project.Project instance>")
    return project


def header(version):
    return (f"# Generated by centurion {version} from {layout.PROJECT_FILE}. Do not edit:\n"
            f"# change the project settings (or vendor a newer centurion) and run `{layout.START_CMD} generate`.\n")


def generated(version):
    out = {}
    for g in all_graphs():
        problems = g.issues()
        if problems:
            raise SystemExit(f"{g.name}: broken graph:\n" + "\n".join(problems))
        out[f"{layout.WORKFLOWS}/{g.name}.yaml"] = g.to_yaml(header(version))
    return out


def generate(root: Path, version, out=sys.stdout):
    for rel, text in generated(version).items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print(f"wrote {rel}", file=out)
    return 0


def check(root: Path, version, out=sys.stdout):
    bad = 0
    expected = generated(version)
    for rel, text in expected.items():
        p = root / rel
        have = p.read_text() if p.exists() else ""
        if have != text:
            bad += 1
            print(f"{rel} is not what `generate` writes:", file=out)
            out.writelines(difflib.unified_diff(have.splitlines(True), text.splitlines(True), rel, "generated", n=1))
    wf = root / layout.WORKFLOWS
    for p in sorted(wf.glob(layout.WORKFLOW_PREFIX + "*.yaml")) if wf.is_dir() else []:
        rel = f"{layout.WORKFLOWS}/{p.name}"
        if rel not in expected:
            bad += 1
            print(f"{rel}: not generated by this centurion (delete it or run generate)", file=out)
    if bad:
        print(f"run `{layout.START_CMD} generate`", file=out)
        return 1
    print(f"centurion {version}: {len(expected)} workflows up to date", file=out)
    return 0


