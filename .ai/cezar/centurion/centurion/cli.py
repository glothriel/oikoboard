GITIGNORE = "state/\n__pycache__/\n"


def vendor(src: Path, root: Path, out=sys.stdout):
    src = src.resolve()
    pkg = src / "centurion"
    if not (pkg / "__init__.py").is_file():
        raise SystemExit(f"{src} is not a centurion checkout (no centurion/__init__.py)")
    home = root / layout.HOME
    home.mkdir(parents=True, exist_ok=True)
    dest = home / "centurion"
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(pkg, dest, ignore=shutil.ignore_patterns("__pycache__"))
    p = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"], capture_output=True, text=True)
    version = p.stdout.strip() if p.returncode == 0 else "unknown"
    dirty = subprocess.run(["git", "-C", str(src), "status", "--porcelain", "--", "centurion"],
                           capture_output=True, text=True).stdout.strip()
    version += "-dirty" if dirty else ""
    (home / "VERSION").write_text(version + "\n")
    (home / "run.py").write_text(runtime.ENTRY_TEXT)
    (home / ".gitignore").write_text(GITIGNORE)
    if not (home / "project.py").exists():
        (home / "project.py").write_text(PROJECT_TEMPLATE)
        print(f"wrote {layout.PROJECT_FILE}: adjust it, then run `{layout.START_CMD} generate`", file=out)
    print(f"vendored centurion {version} into {layout.HOME}", file=out)
    # generate with the freshly vendored code and the repository's project.py
    return subprocess.run([sys.executable, str(home / "run.py"), "generate"], cwd=root).returncode


def read_version(entry: Path):
    v = entry.parent / "VERSION"
    if v.exists():
        return v.read_text().strip()
    from . import __version__
    return __version__


def main(argv=None, entry=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if entry is not None:
        root = runtime.find_root(entry) or Path.cwd()
        project_file = entry.parent / "project.py"
        version = read_version(entry)
    else:  # python3 -m centurion, from a repository root (bootstrap: vendor)
        root = Path.cwd()
        project_file = root / layout.PROJECT_FILE
        version = read_version(root / layout.ENTRY)

    parser = argparse.ArgumentParser(prog=f"python3 {layout.ENTRY}", description="centurion: cezar workflows "
                                     "from issue to reviewed PR", formatter_class=argparse.RawDescriptionHelpFormatter,
                                     epilog="workflow steps (run by the generated workflows):\n" + "\n".join(
                                         f"  {s.name} {s.usage}".rstrip() + f"\n      {s.doc}" for s in STEPS.values()))
    sub = parser.add_subparsers(dest="cmd", metavar="command")
    sub.add_parser("generate", help="write the workflows")
    sub.add_parser("check", help="fail when the committed workflows are not what generate writes")
    v = sub.add_parser("vendor", help="copy centurion from a checkout, stamp VERSION, regenerate")
    v.add_argument("checkout")
    sub.add_parser("automations", help="print the cezar automations as JSON")
    sub.add_parser("steps", help="list the workflow steps")
    for s in STEPS.values():
        sp = sub.add_parser(s.name, help=s.doc, add_help=False)
        sp.add_argument("args", nargs=argparse.REMAINDER)
    if not argv:
        parser.print_help()
        return 2
    ns = parser.parse_args(argv)

    if ns.cmd == "vendor":
        return vendor(Path(ns.checkout), root)
    if ns.cmd == "automations":
        print(json.dumps(automations(), indent=2))
        return 0
    if ns.cmd == "steps":
        for s in STEPS.values():
            print(f"{s.name} {s.usage}".rstrip() + f"\n    {s.doc}")
        return 0
    if ns.cmd in ("generate", "check"):
        load_project(project_file)  # a broken project.py fails here, not in a run
        return (generate if ns.cmd == "generate" else check)(root, version)

    ctx = Ctx(root, load_project(project_file), version=version)
    s = STEPS[ns.cmd]
    try:
        if s.start:
            runtime.take_snapshot(ctx)
        return s.fn(ctx, ns.args) or 0
    except StepError as e:
        print(e, flush=True)
        return e.code
    except (GitError, GhError, NotConfigured) as e:
        sys.stdout.flush()
        print(f"{ns.cmd}: {e}", file=sys.stderr)
        return 1
