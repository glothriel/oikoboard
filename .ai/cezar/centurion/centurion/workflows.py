"""The three workflows. The flow is fixed here; agents only fill single steps, the check nodes run
the steps of steps.py (the same code that names them here, so graph and runtime cannot drift)."""

from . import layout
from .graph import Graph
from .steps import STEPS

P = layout.PROMPTS   # role prompts, from the run's snapshot
S = layout.STATE     # agent-facing run files
R = layout.RULES     # the repository rules, from the run's snapshot
C = layout.CMD       # every later step: the snapshot's entry


def cmd(step, *args):
    s = STEPS[step]  # KeyError: a node names a step that does not exist
    if s.tool:
        raise ValueError(f"{step} is a tool, not a workflow step")
    base = layout.START_CMD if s.start else C
    return " ".join([base, step, *args])


def check(g, id, name, step, *args):
    return g.check(id, name, cmd(step, *args), step, args)


FUSE = 100  # loop nodes only stop runaway runs; the real budgets are counted per task and round


def budget(g, id, name, tries):
    """A retry budget of `tries` per task (and per review round). cezar's loop counters never reset
    within a run, so the loop node is only a fuse and the `retry` step does the counting."""
    g.loop(id, f"{name} fuse", FUSE)
    check(g, f"{id}-left", f"{name} left?", "retry", id, str(tries))
    g.budgets = getattr(g, "budgets", set()) | {id}


def wire_budgets(g):
    """Route every budget loop's repeat port through its guard; out of budget: escalate."""
    edges = []
    for frm, to in g.edges:
        node, _, port = frm.partition(".")
        if node in getattr(g, "budgets", ()) and port == "repeat":
            edges += [(frm, f"{node}-left"), (f"{node}-left.pass", to), (f"{node}-left.fail", "escalate")]
        else:
            edges.append((frm, to))
    g.edges = edges


def format_fix(g, id, validate_node, cont):
    return g.agent(id, "Planner fixes format", f"""
`{C} validate-plan` found problems:

{{{{nodes.{validate_node}.output}}}}

Fix the plan files.
""", cont=cont)


def plan_graph():
    g = Graph("centurion-plan",
              "From a labelled issue to a reviewed plan PR (intent, then spec + tasks). Open product questions go to "
              "the human on the issue first; the planner and the plan reviewer argue with memory; a human reviews "
              "the result. Generated by centurion.")
    g.start()
    check(g, "init", "Read issue", "plan-init")
    g.comment("intent first: open product questions go to the human on the issue, the run stops until answered")
    g.agent("intent", "Intent", f"""
You are the PLANNER. {{{{task}}}}
First settle the intent, following `{P}/intent.md`. Write no spec or plan yet.
""", verdicts=["clear", "questions"])
    check(g, "ask-intent", "Ask about the intent", "ask-issue", "intent")
    check(g, "post-intent", "Post intent", "intent-post")
    g.agent("planner", "Planner", f"""
The intent is settled (`{S}/intent.md`). Now write the spec and the tasks for it,
following `{P}/planner.md` and the repository rules in `{R}`.
If a technical question still blocks the plan, write the numbered questions to
`{S}/questions.md`, write no plan, and end with verdict questions. Otherwise end
with verdict ready.
""", verdicts=["ready", "questions"], cont="intent")
    check(g, "ask", "Ask on the issue", "ask-issue", "plan")

    check(g, "validate", "Validate plan", "validate-plan")
    budget(g, "vloop", "Format fixes", 3)
    format_fix(g, "replan", "validate", "planner")
    check(g, "open", "Open plan PR", "open-pr")

    g.comment("UI mockups: a designer prototypes the views the plan changes; screenshots go to the plan PR, the")
    g.comment("prototype code is kept on centurion-mockups/issue-<n> and the planner points the UI tasks at it")
    check(g, "ui-plan", "UI in the plan?", "screens-check", "plan")
    g.if_contains("needs-mockups", "Mockups needed?", "ui-plan", "needed")
    check(g, "mock-base", "Remember plan commit", "mock-base")
    g.agent("designer", "Designer", f"""
You are the DESIGNER. {{{{task}}}}
Follow `{P}/designer.md` and the repository rules in `{R}`. The plan is the spec and the
tasks this branch adds (`{C} plan-files`): prototype every view the plan adds or changes
(the spec's `## UI` section), screenshot each one and leave the final PNGs and `captions.md`
in `{S}/screens/`. Do not change the plan files.
""")
    check(g, "mock-publish", "Post mockups", "screens-publish", "designer")
    budget(g, "mloop", "Mockup retries", 2)
    g.agent("designer-again", "Designer retries", f"""
Publishing failed:

{{{{nodes.mock-publish.output}}}}

Leave the final screenshots in `{S}/screens/`.
""", cont="designer")
    check(g, "mock-save", "Keep prototype on a branch", "mock-save")
    g.agent("mock-plan", "Planner points tasks at mockups", f"""
The designer prototyped the views of your plan:

{{{{nodes.mock-save.output}}}}

If a prototype was kept, the developers should reuse it. Read it (`git fetch -q origin <branch>`,
then `git diff HEAD origin/<branch>`) and add to every task that builds one of these views one
short bullet: "- Mockup: `<branch>` — <which files / widgets to reuse>". In the spec's
`## UI` section add one line naming the branch. Change nothing else in the plan.
""", cont="planner")
    check(g, "validate-m", "Validate plan", "validate-plan")
    budget(g, "vloop-m", "Format fixes", 3)
    format_fix(g, "mfix", "validate-m", "planner")
    check(g, "push-m", "Push plan", "push")

    g.agent("preview", "Plan reviewer", f"""
You are the PLAN REVIEWER. {{{{task}}}}
Follow `{P}/plan-reviewer.md`. The plan must follow `{P}/planner.md` and the repository
rules in `{R}`.
""", verdicts=["approve", "changes"])
    check(g, "post-review", "Post review", "post-comment", "reviewer", "review.md")
    check(g, "guard", "Round guard", "round-guard")
    g.loop("rounds", "Review fuse", 30)
    g.agent("paddress", "Planner answers review", f"""
The plan reviewer asked for changes (full text in `{S}/review.md`). For each point
either change the plan or explain why not. Write your answer per point to
`{S}/answer.md`. Commit nothing.
""", cont="planner")
    check(g, "validate-a", "Validate plan", "validate-plan")
    budget(g, "vloop-a", "Format fixes", 3)
    format_fix(g, "pfix", "validate-a", "planner")
    check(g, "reply", "Push + post answer", "plan-reply")
    g.agent("rereview", "Plan reviewer re-reviews", f"""
The planner answered your points in `{S}/answer.md` and revised the plan. Accept a
justification when it is sound; insist only on what still matters. Rewrite
`{S}/review.md` with what is still open, or the single line "No findings."
""", verdicts=["approve", "changes"], cont="preview")

    check(g, "ready", "Hand to human", "plan-ready")
    check(g, "escalate", "Escalate", "escalate")
    g.end("planned", name="Plan PR ready")
    g.end("asked", name="Questions asked")
    g.end("stuck", status="failed")

    g.edges_from(
        ("start", "init"), ("init.pass", "intent"),
        ("intent.questions", "ask-intent"), ("ask-intent.pass", "asked"),
        ("intent.clear", "post-intent"), ("post-intent.pass", "planner"),
        ("planner.questions", "ask"), ("ask.pass", "asked"),
        ("planner.ready", "validate"),

        ("validate.fail", "vloop"), ("vloop.repeat", "replan"), ("vloop.exhausted", "escalate"),
        ("replan.done", "validate"), ("validate.pass", "open"),
        ("open.pass", "ui-plan"), ("ui-plan.pass", "needs-mockups"),
        ("needs-mockups.true", "mock-base"), ("needs-mockups.false", "preview"),
        ("mock-base.pass", "designer"), ("designer.done", "mock-publish"),
        ("mock-publish.pass", "mock-save"), ("mock-publish.fail", "mloop"),
        ("mloop.repeat", "designer-again"), ("mloop.exhausted", "escalate"),
        ("designer-again.done", "mock-publish"),
        ("mock-save.pass", "mock-plan"), ("mock-plan.done", "validate-m"),
        ("validate-m.fail", "vloop-m"), ("vloop-m.repeat", "mfix"), ("vloop-m.exhausted", "escalate"),
        ("mfix.done", "validate-m"), ("validate-m.pass", "push-m"), ("push-m.pass", "preview"),

        ("preview.approve", "ready"), ("preview.changes", "post-review"),
        ("post-review.pass", "guard"), ("guard.pass", "rounds"), ("guard.fail", "escalate"),
        ("rounds.repeat", "paddress"), ("rounds.exhausted", "escalate"),
        ("paddress.done", "validate-a"),
        ("validate-a.fail", "vloop-a"), ("vloop-a.repeat", "pfix"), ("vloop-a.exhausted", "escalate"),
        ("pfix.done", "validate-a"), ("validate-a.pass", "reply"),
        ("reply.pass", "rereview"), ("rereview.approve", "ready"), ("rereview.changes", "post-review"),

        ("ready.pass", "planned"), ("escalate.pass", "stuck"),
    )
    wire_budgets(g)
    return g


def pr_graph():
    g = Graph("centurion-pr",
              "Reacts to a human review on a centurion PR. Plan PR approved: merge it into the feature branch and "
              "implement task by task, one PR per task into the feature branch, then open the final PR. Plan "
              "reviewed: the planner revises. Final PR reviewed: the review becomes a task. Label resume on the "
              "issue: back into the task loop. Generated by centurion.")
    g.start()
    check(g, "gate", "Read review", "review-gate")
    g.if_contains("is-resume", "Resume?", "gate", "resume")
    g.if_contains("is-approve", "Plan approved?", "gate", "approve-plan")
    g.if_contains("is-impl", "Final PR reviewed?", "gate", "changes-final")
    g.if_contains("is-plan", "Plan reviewed?", "gate", "changes-plan")
    check(g, "start-impl", "Start implementation", "start-impl")
    check(g, "add-task", "Review becomes a task", "add-review-task")

    g.comment("---- task loop: one task at a time, developer and reviewer keep their sessions within a task")
    g.loop("tasks", "Task fuse", 30)
    g.comment("the feature branch takes in the main branch before every task and before the final PR")
    check(g, "sync", "Merge main branch", "sync-main")
    g.if_contains("is-synced", "Up to date?", "sync", "up-to-date")
    check(g, "sync-verify", "Check merge", "sync-check")
    budget(g, "syncloop", "Merge fixes", 5)
    g.agent("resolve", "Developer resolves merge", f"""
You are the DEVELOPER. Merging the main branch into this issue's feature branch needs you.
`{S}/conflicts.md` lists the conflicted files and what each side did; follow
`{P}/developer.md` and the repository rules in `{R}`. The check after the merge said:

{{{{nodes.sync-verify.output}}}}

Resolve every conflict in the work tree so that both sides' changes keep working: the main
branch is already released, so adapt the feature branch's side. Then run `{C} sync-check`
(conflict markers and the validation commands) and fix what it reports. Do not commit, push or
comment: the workflow does that.
""")
    check(g, "sync-push", "Push merge", "sync-push")
    check(g, "next", "Next task", "next-task")
    g.if_contains("no-task", "All done?", "next", "NONE")
    g.agent("implement", "Developer", f"""
You are the DEVELOPER on one task of a plan. Follow `{P}/developer.md` and the repository
rules in `{R}`. The task is in `{S}/current-task.md`.
""")
    check(g, "tests", "Verify", "verify")
    check(g, "task-pr", "Open task PR", "task-pr")
    budget(g, "fixes", "Verify fixes", 10)
    g.agent("fix", "Developer fixes verify", f"""
`{C} verify` failed:

{{{{nodes.tests.output}}}}

Fix the cause, not the tests.
""", cont="implement")
    g.agent("review", "Reviewer", f"""
You are the REVIEWER of one task of a plan. Follow `{P}/reviewer.md` and the repository rules
in `{R}`. The task is in `{S}/current-task.md`; its change is `{C} task-diff`.
""", verdicts=["approve", "changes"])
    check(g, "post-review", "Post review", "post-comment", "reviewer", "review.md")
    check(g, "guard", "Round guard", "round-guard")
    g.loop("rounds", "Review fuse", 30)
    g.agent("address", "Developer answers review", f"""
The reviewer asked for changes (full text in `{S}/review.md`). For each finding
either fix it or explain why it is wrong or not worth it. Write your answer per finding to
`{S}/reply.md`. Run `{C} verify` before you finish.
""", cont="implement")
    check(g, "tests-a", "Verify", "verify")
    budget(g, "fixes-a", "Verify fixes", 10)
    g.agent("fix-a", "Developer fixes verify", f"""
`{C} verify` failed:

{{{{nodes.tests-a.output}}}}

Fix the cause, not the tests.
""", cont="implement")
    check(g, "post-reply", "Push + post reply", "task-reply")
    g.agent("rereview", "Reviewer re-reviews", f"""
The developer answered your findings in `{S}/reply.md` and changed the code
(`{C} task-diff` is the whole task so far). Accept a justification
when it is sound; insist only on what still matters. Rewrite `{S}/review.md` with
what is still open, or the single line "No findings."
""", verdicts=["approve", "changes"], cont="review")
    check(g, "done-task", "Task approved", "mark-done")
    check(g, "impl-ready", "Open final PR", "impl-ready")

    g.comment("---- plan reviewed by a human: a fresh planner revises it")
    g.agent("replanner", "Planner revises", f"""
You are the PLANNER. A human reviewed the plan on this PR; the review is in
`{S}/human-review.md`. The plan is the spec and the tasks this branch adds
(`{C} plan-files`). Follow `{P}/planner.md` and the repository rules in `{R}`.
Change the plan or explain why not, for each point, and write your answer per point to
`{S}/answer.md`. Commit nothing.
If the review or your changes affect how the views of the plan look or behave (including comments
on the mockups), write the single line `redo` to `{S}/mockups`: a designer then
reworks the mockups.
""")
    check(g, "pvalidate", "Validate plan", "validate-plan")
    budget(g, "ploop", "Format fixes", 3)
    format_fix(g, "pfix", "pvalidate", "replanner")
    g.comment("the revised plan changes the UI: the designer reworks the prototype, new mockups go to the PR")
    check(g, "remock", "Mockups to redo?", "remock-check")
    g.if_contains("needs-remock", "Redo mockups?", "remock", "needed")
    check(g, "mock-restore", "Restore prototype", "mock-restore")
    g.agent("designer", "Designer", f"""
You are the DESIGNER. A human reviewed the plan on this PR (`{S}/human-review.md`)
and the planner revised it (`{S}/answer.md`). The plan is the spec and the tasks
this branch adds (`{C} plan-files`). The previous prototype:

{{{{nodes.mock-restore.output}}}}

Follow `{P}/designer.md` and the repository rules in `{R}`: rework the prototype so it
shows every view of the revised plan (the spec's `## UI` section), screenshot each new or changed
one and leave the final PNGs and `captions.md` (say what changed since the last mockups) in
`{S}/screens/`. Do not change the plan files.
""")
    check(g, "mock-publish", "Post mockups", "screens-publish", "designer")
    budget(g, "mloop", "Mockup retries", 2)
    g.agent("designer-again", "Designer retries", f"""
Publishing failed:

{{{{nodes.mock-publish.output}}}}

Leave the final screenshots in `{S}/screens/`.
""", cont="designer")
    check(g, "mock-save", "Keep prototype on a branch", "mock-save")
    g.agent("mock-plan", "Planner points tasks at mockups", f"""
The designer reworked the prototype for your revised plan:

{{{{nodes.mock-save.output}}}}

If a prototype was kept, the developers should reuse it. Read it (`git fetch -q origin <branch>`,
then `git diff HEAD origin/<branch>`) and make sure every task that builds one of these views has
one up-to-date short bullet: "- Mockup: `<branch>` — <which files / widgets to reuse>", and the spec's
`## UI` section names the branch. Change nothing else in the plan.
""", cont="replanner")
    check(g, "validate-m", "Validate plan", "validate-plan")
    budget(g, "vloop-m", "Format fixes", 3)
    format_fix(g, "mfix", "validate-m", "replanner")
    check(g, "answered", "Push + answer", "plan-answered")

    check(g, "escalate", "Escalate", "escalate")
    g.end("skipped", name="Nothing to do")
    g.end("done")
    g.end("stuck", status="failed")

    g.edges_from(
        ("start", "gate"), ("gate.pass", "is-resume"),
        ("is-resume.true", "tasks"), ("is-resume.false", "is-approve"),
        ("is-approve.true", "start-impl"), ("is-approve.false", "is-impl"),
        ("is-impl.true", "add-task"), ("is-impl.false", "is-plan"),
        ("is-plan.true", "replanner"), ("is-plan.false", "skipped"),
        ("start-impl.pass", "tasks"), ("add-task.pass", "tasks"),

        ("tasks.repeat", "sync"), ("tasks.exhausted", "escalate"),
        ("sync.pass", "is-synced"),
        ("is-synced.true", "next"), ("is-synced.false", "sync-verify"),
        ("sync-verify.pass", "sync-push"), ("sync-verify.fail", "syncloop"),
        ("syncloop.repeat", "resolve"), ("syncloop.exhausted", "escalate"),
        ("resolve.done", "sync-verify"), ("sync-push.pass", "next"),
        ("next.pass", "no-task"),
        ("no-task.true", "impl-ready"), ("no-task.false", "implement"),
        ("implement.done", "tests"), ("tests.pass", "task-pr"),
        ("task-pr.pass", "review"),
        ("tests.fail", "fixes"), ("fixes.repeat", "fix"), ("fixes.exhausted", "escalate"),
        ("fix.done", "tests"),
        ("review.approve", "done-task"), ("review.changes", "post-review"),
        ("post-review.pass", "guard"), ("guard.pass", "rounds"), ("guard.fail", "escalate"),
        ("rounds.repeat", "address"), ("rounds.exhausted", "escalate"),
        ("address.done", "tests-a"),
        ("tests-a.pass", "post-reply"), ("tests-a.fail", "fixes-a"),
        ("fixes-a.repeat", "fix-a"), ("fixes-a.exhausted", "escalate"),
        ("fix-a.done", "tests-a"),
        ("post-reply.pass", "rereview"),
        ("rereview.approve", "done-task"), ("rereview.changes", "post-review"),
        ("done-task.pass", "tasks"), ("impl-ready.pass", "done"),

        ("replanner.done", "pvalidate"),
        ("pvalidate.fail", "ploop"), ("ploop.repeat", "pfix"), ("ploop.exhausted", "escalate"),
        ("pfix.done", "pvalidate"), ("pvalidate.pass", "remock"),
        ("remock.pass", "needs-remock"),
        ("needs-remock.false", "answered"), ("needs-remock.true", "mock-restore"),
        ("mock-restore.pass", "designer"), ("designer.done", "mock-publish"),
        ("mock-publish.pass", "mock-save"), ("mock-publish.fail", "mloop"),
        ("mloop.repeat", "designer-again"), ("mloop.exhausted", "escalate"),
        ("designer-again.done", "mock-publish"),
        ("mock-save.pass", "mock-plan"), ("mock-plan.done", "validate-m"),
        ("validate-m.fail", "vloop-m"), ("vloop-m.repeat", "mfix"), ("vloop-m.exhausted", "escalate"),
        ("mfix.done", "validate-m"), ("validate-m.pass", "answered"),
        ("answered.pass", "done"),

        ("escalate.pass", "stuck"),
    )
    wire_budgets(g)
    return g


def cleanup_graph():
    g = Graph("centurion-cleanup",
              "A centurion PR was merged or closed. When the issue's work is over (final PR merged or closed, plan "
              "PR closed unmerged), delete all its branches. Generated by centurion.")
    g.start()
    check(g, "cleanup", "Delete the issue's branches", "cleanup")
    g.end("done")
    g.end("failed", status="failed")
    g.edges_from(("start", "cleanup"), ("cleanup.pass", "done"), ("cleanup.fail", "failed"))
    return g


def all_graphs():
    return [plan_graph(), pr_graph(), cleanup_graph()]
